"""Every supported book format opens and yields sensible chapters.

Two groups: small books generated by tests/samples.py, and your own books from books/ and data/
(add any files there; each one becomes a test).
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from ai_reader.books import load_book
from ai_reader.books.headings import HARD_LIMIT

from . import samples

ROOT = Path(__file__).resolve().parents[1]
BOOK_FOLDERS = (ROOT / "books", ROOT / "data")
BOOK_SUFFIXES = (".txt", ".fb2", ".fb2.zip", ".zip", ".epub", ".pdf", ".html", ".htm", ".xhtml")
MAX_TITLE = 200
_MARKUP = re.compile(r"</?(?:p|div|span|br|section|title|body|html|td|tr)\b[^>]*>|&nbsp;|&#\d+;", re.IGNORECASE)

GENERATED = {
    "txt-utf8": (lambda folder: samples.make_txt(folder, "utf-8"), samples.PHRASE),
    "txt-cp1251": (lambda folder: samples.make_txt(folder, "cp1251"), samples.PHRASE),
    "fb2": (samples.make_fb2, samples.PHRASE),
    "fb2.zip": (samples.make_fb2_zip, samples.PHRASE),
    "epub": (samples.make_epub, samples.PHRASE),
    "html": (samples.make_html, samples.PHRASE),
    "pdf": (samples.make_pdf, samples.LATIN_PHRASE),
}


def _own_books() -> list[Path]:
    found = []
    for folder in BOOK_FOLDERS:
        if folder.is_dir():
            found += [p for p in sorted(folder.rglob("*")) if p.is_file() and p.name.lower().endswith(BOOK_SUFFIXES)]
    return found


def check_book(book) -> None:
    """What any opened book must satisfy, whatever its format."""
    assert book.title.strip(), "книга без названия"
    assert book.chapters, "не найдено ни одной главы"
    for number, chapter in enumerate(book.chapters, 1):
        where = f"глава {number} «{chapter.title[:40]}»"
        assert chapter.title.strip(), f"{where}: пустое название"
        assert len(chapter.title) <= MAX_TITLE, f"{where}: слишком длинное название"
        assert "\n" not in chapter.title, f"{where}: перенос строки в названии"
        assert chapter.text.strip(), f"{where}: пустой текст"
        assert len(chapter.text) <= HARD_LIMIT, f"{where}: {len(chapter.text)} знаков — глава не разделена"
        leftover = _MARKUP.search(chapter.text)
        assert leftover is None, f"{where}: остатки разметки {leftover.group(0)!r}"


@pytest.mark.parametrize("kind", GENERATED)
def test_generated_book(kind: str, tmp_path: Path) -> None:
    make, phrase = GENERATED[kind]
    book = load_book(make(tmp_path))
    check_book(book)
    text = "\n".join(chapter.text for chapter in book.chapters)
    assert phrase in text
    assert "var x" not in text and "color:red" not in text  # scripts and styles are not book text
    if kind != "html":  # an HTML page is one text unless it is long
        assert len(book.chapters) == 2
        assert "2" in book.chapters[1].title


def test_fb2_metadata(tmp_path: Path) -> None:
    book = load_book(samples.make_fb2(tmp_path))
    assert (book.title, book.author, book.language) == ("Пробная книга", "Иван Тестов", "ru")
    assert [chapter.title for chapter in book.chapters] == [title for title, _paragraphs in samples.CHAPTERS]


def test_parallel_fb2_keeps_one_language_and_finds_chapters(tmp_path: Path) -> None:
    book = load_book(samples.make_parallel_fb2(tmp_path))
    check_book(book)
    assert [chapter.title for chapter in book.chapters] == ["Часть первая — I", "Часть первая — II"]
    assert not re.search(r"[A-Za-z]{3,}", "".join(chapter.text for chapter in book.chapters))


def test_unreadable_book_is_reported(tmp_path: Path) -> None:
    empty = tmp_path / "empty.txt"
    empty.write_text("   \n\n", encoding="utf-8")
    with pytest.raises(ValueError):
        load_book(empty)


@pytest.mark.parametrize("path", _own_books(), ids=lambda p: p.name)
def test_own_book(path: Path) -> None:
    book = load_book(path)
    check_book(book)
    print(f"\n{path.name}: {len(book.chapters)} глав, {book.total_chars} знаков")
